-- 0059_content_item_published_at :: up
-- Витрина «новое на этой неделе» + бейдж New (growth-волна 1, G1-2) считали свежесть
-- по `created_at` — времени ИМПОРТА. Реальный поток другой: файл заливается ботом,
-- лежит черновиком до ревью, публикуется днями позже — и в каталог такой тест
-- приходит уже «не новым». Дата публикации фиксируется отдельно.
--
-- Nullable без дефолта: колонка осмысленна только для опубликованных строк, а
-- черновику «дата публикации» не нужна (NOT NULL DEFAULT now() соврал бы про
-- каждый draft). Постуру наследует от content_item (публичные колонки), новых
-- грантов/политик не требуется.

ALTER TABLE content_item ADD COLUMN published_at timestamptz;

-- Бэкфилл: у всего, что уже опубликовано, единственная известная дата — created_at.
-- Без него каждый живой тест каталога разом стал бы «нулевой свежести» (NULL) и
-- потребители читали бы неопределённость вместо факта.
UPDATE content_item SET published_at = created_at WHERE status = 'published';
