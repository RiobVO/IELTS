-- 0060_attempt_share_token :: up
-- Band-карточка для шеринга (growth-волна 1, G1-5). Чтобы ссылка разворачивалась
-- превью в Telegram, страница и og:image ОБЯЗАНЫ быть доступны без сессии: краулер
-- мессенджера ходит анонимно, owner-гейт превратил бы карточку в пустой прямоугольник.
-- Поэтому доступ даёт неугадываемый токен, а не id попытки:
--   * выдаётся ТОЛЬКО владельцу и только для СДАННОЙ попытки (server action);
--   * лениво — пока юзер не нажал Share, строка NULL и делиться нечем;
--   * отдельный от attempt.id, чтобы публичная ссылка не светила внутренний id,
--     которым адресуются owner-scoped маршруты (/result?a=…), и чтобы шеринг можно
--     было отозвать одним UPDATE ... SET share_token = NULL.
-- Публичная страница читает по токену band, слабейший тип и заголовок теста —
-- ни ответов, ни ключа, ни персональных данных.

ALTER TABLE attempt ADD COLUMN share_token uuid;

-- UNIQUE даёт и защиту от коллизии, и индекс под единственный публичный запрос
-- (WHERE share_token = $1). Partial — NULL'ы (подавляющее большинство строк) в
-- индекс не попадают.
CREATE UNIQUE INDEX attempt_share_token_key ON attempt (share_token)
  WHERE share_token IS NOT NULL;

