// Вердикт бота показывает правильный ответ (verdictMessage). Это безопасно ровно
// потому, что разбор сданной попытки сейчас открыт всем тарифам: REVIEW_OPEN = true.
// Если флаг когда-нибудь закроют обратно под Premium, бот станет обходным путём
// к платному разбору — из чата, мимо тарифного гейта. Тест не даёт этому случиться
// молча: он падает в момент переключения флага и требует решить, что делает бот.
import { describe, it, expect } from "vitest";
import { REVIEW_OPEN } from "@/lib/tiers";
import { verdictMessage } from "./messages";

describe("бот раскрывает ответ — сцепка с тарифным гейтом разбора", () => {
  it("вердикт называет правильный ответ", () => {
    expect(verdictMessage({ correct: false, expected: "TRUE", reviewUrl: null })).toContain("TRUE");
  });

  it("разбор открыт всем — иначе бот стал бы обходом Premium", () => {
    // Уронили этот тест переключением REVIEW_OPEN? Ответ бота нужно закрыть тем же
    // гейтом (hasFullReview по тарифу автора попытки) ИЛИ убрать `expected` из
    // вердикта. Просто поправить ожидание здесь — значит открыть утечку.
    expect(REVIEW_OPEN).toBe(true);
  });
});
